//! AMCTRL and NPDRM key material.
//!
//! Like the KIRK key vault these are published constants recovered from the
//! PSP firmware years ago, carried by every emulator and tool that touches
//! NPDRM content. They are not secrets, but they are still key material:
//! never log them.
//!
//! The three `AMCTRL_KEY*` values are whitening constants rather than cipher
//! keys — they are XORed into intermediate state, never handed to AES as a
//! key. Which one applies where is documented at each use site.

